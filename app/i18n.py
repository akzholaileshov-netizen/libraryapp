def get_lang() -> str:
    lang = (session.get("lang") or DEFAULT_LANG).lower()
    return lang if lang in SUPPORTED_LANGS else DEFAULT_LANG


def set_lang(lang: str) -> str:
    code = (lang or DEFAULT_LANG).lower()
    if code not in SUPPORTED_LANGS:
        code = DEFAULT_LANG
    session["lang"] = code
    return code


def t(key: str) -> str:
    lang = get_lang()
    return TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANG]).get(
        key,
        TRANSLATIONS[DEFAULT_LANG].get(key, key),
    )


def localized_book_field(book, field: str) -> str:
    """field: title | genre | content — тілге сәйкес баған."""
    lang = get_lang()
    if lang == "kk":
        return (book[field] or "") if field in book.keys() else ""
    col = f"{field}_{lang}"
    if col in book.keys() and (book[col] or "").strip():
        return book[col]
    return (book[field] or "") if field in book.keys() else ""
